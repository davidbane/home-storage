// Writes docs/design-system/tokens.md from src/tokens.json, so the token reference
// can't drift from the code. Run: yarn tokens:docs (from the repo root).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(resolve(here, '../src/tokens.json'), 'utf8'));
const out = resolve(here, '../../../docs/design-system/tokens.md');
mkdirSync(dirname(out), { recursive: true });

const themes = tokens.color.themes;
const first = themes[0].id;
const colors = new Map(tokens.color.tokens.map((token) => [token.name, token]));

// Resolve a color token's hex for a theme, following {alias} references.
function hex(name, theme, depth = 0) {
  const token = colors.get(name);
  if (!token || depth > 16) {
    return undefined;
  }
  const value = typeof token.value === 'object' ? (token.value[theme] ?? token.value[first]) : token.value;
  const alias = /^\{(.+)\}$/.exec(value);
  return alias ? hex(alias[1], theme, depth + 1) : value.toLowerCase();
}

// WCAG 2 relative luminance and contrast ratio.
function luminance(hexColor) {
  const channels = [1, 3, 5].map((offset) => parseInt(hexColor.slice(offset, offset + 2), 16) / 255);
  const [red, green, blue] = channels.map((channel) => (channel <= 0.03928 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4));
  return 0.2126 * red + 0.7152 * green + 0.0722 * blue;
}
const ratio = (first, second) => {
  const [lighter, darker] = [luminance(first), luminance(second)].sort((left, right) => right - left);
  return (lighter + 0.05) / (darker + 0.05);
};

const escapeCell = (text = '') => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const lines = [];
const push = (...entries) => lines.push(...entries);

push(
  `# Token reference`,
  '',
  `<!-- Generated by packages/apothecary-tokens/scripts/docs.mjs from tokens.json (${tokens.name} v${tokens.version}). Do not edit by hand; run \`yarn tokens:docs\`. -->`,
  '',
  `Every value here compiles to a CSS custom property \`--ap-<name>\` and, for Tailwind, a utility (\`bg-<color>\`, \`shadow-<name>\`, \`rounded-<name>\`, \`type-<style>\`). Themes: ${themes.map((theme) => `**${theme.name}** (\`${theme.id}\`)`).join(', ')}.`,
  '',
);

// ---- color ----
push(`## Color`, '', `| Token | ${themes.map((theme) => theme.name).join(' | ')} | Usage |`, `|---|${themes.map(() => '---|').join('')}---|`);
for (const token of tokens.color.tokens) {
  const values = themes.map((theme) => {
    const raw = typeof token.value === 'object' ? (token.value[theme.id] ?? token.value[first]) : token.value;
    return /^\{/.test(raw) ? `→ \`${raw.slice(1, -1)}\`` : `\`${hex(token.name, theme.id)}\``;
  });
  push(`| \`${token.name}\` | ${values.join(' | ')} | ${escapeCell(token.usage)} |`);
}

// ---- contrast ----
const textTokens = ['ink', 'ink-muted', 'brass', 'sapphire-ink', 'oxblood-ink', 'verdigris-ink'].filter((name) => colors.has(name));
const surfaces = ['surface-0', 'surface-1', 'surface-2'].filter((name) => colors.has(name));
const pairs = [
  ['on-sapphire', 'sapphire'],
  ['on-sapphire', 'oxblood'],
  ['sapphire-ink', 'sapphire-tint'],
  ['oxblood-ink', 'oxblood-tint'],
  ['verdigris-ink', 'verdigris-tint'],
  ['brass', 'brass-tint'],
  ['on-bottle', 'bottle'],
  ['brass-on-bottle', 'bottle'],
].filter(([foreground, background]) => colors.has(foreground) && colors.has(background));

const cell = (contrastRatio) => `${contrastRatio.toFixed(1)}${contrastRatio < 4.5 ? ' ⚠' : ''}`;
push('', `## Contrast`, '', `WCAG 2 ratios, computed from the values above. Body text needs **4.5:1**; ⚠ marks anything under it.`, '');
for (const theme of themes) {
  push(`### ${theme.name}`, '', `| Text on | ${surfaces.map((surface) => `\`${surface}\``).join(' | ')} |`, `|---|${surfaces.map(() => '---|').join('')}`);
  for (const foreground of textTokens) {
    push(`| \`${foreground}\` | ${surfaces.map((surface) => cell(ratio(hex(foreground, theme.id), hex(surface, theme.id)))).join(' | ')} |`);
  }
  push('', `| Pair | Ratio |`, `|---|---|`);
  for (const [foreground, background] of pairs) {
    push(`| \`${foreground}\` on \`${background}\` | ${cell(ratio(hex(foreground, theme.id), hex(background, theme.id)))} |`);
  }
  push('');
}

// ---- type ----
push(`## Typography`, '', `Families:`, '');
for (const [family, stack] of Object.entries(tokens.type.families)) {
  push(`- \`${family}\`: ${stack}`);
}
push('', `| Style | Family | Size / line | Weight | Usage |`, `|---|---|---|---|---|`);
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    push(`| \`type-${style.name}\` | ${style.family ?? group.family} | ${style.fontSize} / ${style.lineHeight}${style.letterSpacing ? `, ${style.letterSpacing}` : ''} | ${style.fontWeight} | ${escapeCell(style.usage)} |`);
  }
}

// ---- other families ----
const simple = (title, family, prefix) => {
  if (!tokens[family]) {
    return;
  }
  push('', `## ${title}`, '');
  if (tokens[family].note) {
    push(escapeCell(tokens[family].note), '');
  }
  const themed = tokens[family].tokens.some((token) => typeof token.value === 'object');
  if (themed) {
    push(`| Token | ${themes.map((theme) => theme.name).join(' | ')} | Usage |`, `|---|${themes.map(() => '---|').join('')}---|`);
    for (const token of tokens[family].tokens) {
      push(`| \`${prefix(token.name)}\` | ${themes.map((theme) => `\`${escapeCell(typeof token.value === 'object' ? (token.value[theme.id] ?? token.value[first]) : token.value)}\``).join(' | ')} | ${escapeCell(token.usage)} |`);
    }
  } else {
    push(`| Token | Value | Usage |`, `|---|---|---|`);
    for (const token of tokens[family].tokens) {
      push(`| \`${prefix(token.name)}\` | \`${token.value}\` | ${escapeCell(token.usage)} |`);
    }
  }
};
simple('Spacing', 'spacing', (name) => name);
push('', `Spacing matches Tailwind's 4px scale, so \`space-5\` is \`p-5\` / \`gap-5\`.`);
simple('Radius', 'radius', (name) => `rounded-${name.replace(/^radius-/, '')}`);
simple('Depth', 'shadow', (name) => `shadow-${name.replace(/^shadow-/, '')}`);
simple('Layout', 'layout', (name) => name);

writeFileSync(out, lines.join('\n') + '\n');
console.log(`tokens: wrote ${out.replace(resolve(here, '../../..') + '/', '')}`);
