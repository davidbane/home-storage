// Writes docs/design-system/tokens.md from src/tokens.json, so the token reference
// can't drift from the code. Run: yarn tokens:docs (from the repo root).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const tokens = JSON.parse(readFileSync(resolve(here, '../src/tokens.json'), 'utf8'))
const out = resolve(here, '../../../docs/design-system/tokens.md')
mkdirSync(dirname(out), { recursive: true })

const themes = tokens.color.themes
const first = themes[0].id
const colors = new Map(tokens.color.tokens.map((t) => [t.name, t]))

// Resolve a color token's hex for a theme, following {alias} references.
function hex(name, theme, depth = 0) {
  const t = colors.get(name)
  if (!t || depth > 16) return undefined
  const v = typeof t.value === 'object' ? (t.value[theme] ?? t.value[first]) : t.value
  const alias = /^\{(.+)\}$/.exec(v)
  return alias ? hex(alias[1], theme, depth + 1) : v.toLowerCase()
}

// WCAG 2 relative luminance and contrast ratio.
function luminance(h) {
  const c = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255)
  const [r, g, b] = c.map((x) => (x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4))
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}

const esc = (s = '') => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')
const lines = []
const push = (...l) => lines.push(...l)

push(
  `# Token reference`,
  '',
  `<!-- Generated by packages/tokens/scripts/docs.mjs from tokens.json (${tokens.name} v${tokens.version}). Do not edit by hand; run \`yarn tokens:docs\`. -->`,
  '',
  `Every value here compiles to a CSS custom property \`--ap-<name>\` and, for Tailwind, a utility (\`bg-<color>\`, \`shadow-<name>\`, \`rounded-<name>\`, \`type-<style>\`). Themes: ${themes.map((t) => `**${t.name}** (\`${t.id}\`)`).join(', ')}.`,
  '',
)

// ---- color ----
push(`## Color`, '', `| Token | ${themes.map((t) => t.name).join(' | ')} | Usage |`, `|---|${themes.map(() => '---|').join('')}---|`)
for (const t of tokens.color.tokens) {
  const vals = themes.map((th) => {
    const raw = typeof t.value === 'object' ? (t.value[th.id] ?? t.value[first]) : t.value
    return /^\{/.test(raw) ? `→ \`${raw.slice(1, -1)}\`` : `\`${hex(t.name, th.id)}\``
  })
  push(`| \`${t.name}\` | ${vals.join(' | ')} | ${esc(t.usage)} |`)
}

// ---- contrast ----
const textTokens = ['ink', 'ink-muted', 'brass', 'sapphire-ink', 'oxblood-ink', 'verdigris-ink'].filter((n) => colors.has(n))
const surfaces = ['surface-0', 'surface-1', 'surface-2'].filter((n) => colors.has(n))
const pairs = [
  ['on-sapphire', 'sapphire'],
  ['on-sapphire', 'oxblood'],
  ['sapphire-ink', 'sapphire-tint'],
  ['oxblood-ink', 'oxblood-tint'],
  ['verdigris-ink', 'verdigris-tint'],
  ['brass', 'brass-tint'],
  ['on-bottle', 'bottle'],
  ['brass-on-bottle', 'bottle'],
].filter(([a, b]) => colors.has(a) && colors.has(b))

const cell = (r) => `${r.toFixed(1)}${r < 4.5 ? ' ⚠' : ''}`
push('', `## Contrast`, '', `WCAG 2 ratios, computed from the values above. Body text needs **4.5:1**; ⚠ marks anything under it.`, '')
for (const th of themes) {
  push(`### ${th.name}`, '', `| Text on | ${surfaces.map((s) => `\`${s}\``).join(' | ')} |`, `|---|${surfaces.map(() => '---|').join('')}`)
  for (const fg of textTokens) push(`| \`${fg}\` | ${surfaces.map((s) => cell(ratio(hex(fg, th.id), hex(s, th.id)))).join(' | ')} |`)
  push('', `| Pair | Ratio |`, `|---|---|`)
  for (const [fg, bg] of pairs) push(`| \`${fg}\` on \`${bg}\` | ${cell(ratio(hex(fg, th.id), hex(bg, th.id)))} |`)
  push('')
}

// ---- type ----
push(`## Typography`, '', `Families:`, '')
for (const [k, v] of Object.entries(tokens.type.families)) push(`- \`${k}\`: ${v}`)
push('', `| Style | Family | Size / line | Weight | Usage |`, `|---|---|---|---|---|`)
for (const g of tokens.type.groups)
  for (const s of g.styles)
    push(`| \`type-${s.name}\` | ${s.family ?? g.family} | ${s.fontSize} / ${s.lineHeight}${s.letterSpacing ? `, ${s.letterSpacing}` : ''} | ${s.fontWeight} | ${esc(s.usage)} |`)

// ---- other families ----
const simple = (title, family, prefix) => {
  if (!tokens[family]) return
  push('', `## ${title}`, '')
  if (tokens[family].note) push(esc(tokens[family].note), '')
  const themed = tokens[family].tokens.some((t) => typeof t.value === 'object')
  if (themed) {
    push(`| Token | ${themes.map((t) => t.name).join(' | ')} | Usage |`, `|---|${themes.map(() => '---|').join('')}---|`)
    for (const t of tokens[family].tokens)
      push(`| \`${prefix(t.name)}\` | ${themes.map((th) => `\`${esc(typeof t.value === 'object' ? (t.value[th.id] ?? t.value[first]) : t.value)}\``).join(' | ')} | ${esc(t.usage)} |`)
  } else {
    push(`| Token | Value | Usage |`, `|---|---|---|`)
    for (const t of tokens[family].tokens) push(`| \`${prefix(t.name)}\` | \`${t.value}\` | ${esc(t.usage)} |`)
  }
}
simple('Spacing', 'spacing', (n) => n)
push('', `Spacing matches Tailwind's 4px scale, so \`space-5\` is \`p-5\` / \`gap-5\`.`)
simple('Radius', 'radius', (n) => `rounded-${n.replace(/^radius-/, '')}`)
simple('Depth', 'shadow', (n) => `shadow-${n.replace(/^shadow-/, '')}`)
simple('Layout', 'layout', (n) => n)

writeFileSync(out, lines.join('\n') + '\n')
console.log(`tokens: wrote ${out.replace(resolve(here, '../../..') + '/', '')}`)
